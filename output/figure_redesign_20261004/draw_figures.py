INK='#23282D'; GRAY='#647078'; LIGHT='#CDD2D6'; BLUE='#245F87'; PALE='#E7EFF5'; ACCENT='#AA623A'
TEXT=[]
FIGURE_WIDTH_IN = 180 / 25.4

def canvas(height=84):
    fig=plt.figure(figsize=(FIGURE_WIDTH_IN,height/25.4))
    ax=fig.add_axes([0,0,1,1]);ax.set(xlim=(0,180),ylim=(0,height));ax.set_axis_off()
    return fig,ax

def text(ax,x,y,s,size=7,color=INK,weight='normal',ha='left',va='center',**kw):
    t=ax.text(x,y,s,fontsize=size,color=color,weight=weight,ha=ha,va=va,
              linespacing=1.22,**kw);TEXT.append(t);return t

def line(ax,pts,color=GRAY,lw=.7,ls='-',z=1):
    ax.plot([p[0] for p in pts],[p[1] for p in pts],color=color,lw=lw,ls=ls,
            solid_capstyle='butt',zorder=z)

def arrow(ax,start,end,color=GRAY,lw=.85,rad=0,style='-',shrink=0,head=5):
    p=FancyArrowPatch(start,end,arrowstyle='-|>',mutation_scale=head,
                      connectionstyle=f'arc3,rad={rad}',linewidth=lw,
                      color=color,linestyle=style,shrinkA=shrink,shrinkB=shrink,zorder=2)
    ax.add_patch(p);return p

def flow(ax,pts,color=BLUE,lw=.85):
    line(ax,pts[:-1],color,lw)
    arrow(ax,pts[-2],pts[-1],color,lw,head=6)

def node(ax,x,y,label='',r=2.1,color=GRAY,fill='white',lw=.8,size=6.6):
    ax.add_patch(Circle((x,y),r,facecolor=fill,edgecolor=color,lw=lw,zorder=4))
    if label:text(ax,x,y,label,size,color,ha='center',zorder=5)

def edge(ax,a,b,r=2.1,color=GRAY,lw=.65,rad=0,ls='-'):
    dx=b[0]-a[0];dy=b[1]-a[1];d=math.hypot(dx,dy)
    s=(a[0]+dx/d*(r+.3),a[1]+dy/d*(r+.3))
    e=(b[0]-dx/d*(r+.5),b[1]-dy/d*(r+.5))
    arrow(ax,s,e,color,lw,rad,ls,head=4.6)

def panel(ax,x,y,letter,title,right):
    text(ax,x,y,letter,9,weight='bold')
    text(ax,x+4.3,y,title,7.7,weight='bold')
    line(ax,[(x,y-3.5),(right,y-3.5)],LIGHT,.65)

def graph(ax,coords,edges,focus=(),r=2.1):
    for u,v in edges:edge(ax,coords[u],coords[v],r=r)
    for k,(x,y) in coords.items():node(ax,x,y,k,r,BLUE if k in focus else GRAY,
                                      PALE if k in focus else 'white')

def save(fig,stem):
    fig.canvas.draw()
    ren=fig.canvas.get_renderer();bb=fig.bbox
    clipped=[]
    for t in TEXT:
        if t.figure is fig:
            tb=t.get_window_extent(ren)
            if tb.x0 < bb.x0 or tb.x1 > bb.x1 or tb.y0 < bb.y0 or tb.y1 > bb.y1:
                clipped.append(t.get_text())
    assert not clipped,clipped
    fig.savefig(OUT/f'{stem}.svg')
    fig.savefig(OUT/f'{stem}.pdf')
    fig.savefig(OUT/f'{stem}.png',dpi=300)
    # Same geometry in grayscale, generated by the selected Python backend.
    from matplotlib.colors import to_rgba
    for art in fig.findobj():
        for getter,setter in [('get_color','set_color'),('get_facecolor','set_facecolor'),('get_edgecolor','set_edgecolor')]:
            if hasattr(art,getter) and hasattr(art,setter):
                try:
                    r,g,b,a=to_rgba(getattr(art,getter)());lum=.2126*r+.7152*g+.0722*b
                    getattr(art,setter)((lum,lum,lum,a))
                except (ValueError,TypeError):pass
    fig.savefig(OUT/'qa'/f'{stem}_grayscale.png',dpi=300)
    plt.close(fig)

