#!/usr/bin/env python3
"""Generate the new replay appendix from frozen, complete experiment values."""
from pathlib import Path
import hashlib
import json
import math

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / '2026NAACL/SA-MCGS/experiments/component_mechanisms_20261010/EXPERIMENT_TABLES_20261011_values.json'
TARGET = ROOT / 'paper/latex/revision_core_ablation_20261011.tex'
MODELS = ('llama', 'qwen35', 'kimi')
NAMES = {'llama': 'Llama 3.1-8B-Instruct', 'qwen35': 'Qwen3.5-9B', 'kimi': 'Kimi-VL-A3B'}
METRICS = ('root_at_3', 'risk_any', 'risk_all', 'compression')


def fmt(value):
    return f'{value:.2f}'


def marked(value, others, metric):
    text = fmt(value)
    if metric == 'compression':
        return text
    distinct = sorted({round(x, 10) for x in others}, reverse=True)
    if math.isclose(value, distinct[0], abs_tol=1e-8):
        return r'\tblbest{' + text + '}'
    if len(distinct) > 1 and math.isclose(value, distinct[1], abs_tol=1e-8):
        return r'\tblsecond{' + text + '}'
    return text


def table(rows, caption, label, header=None):
    header = header or r'\bfseries Policy & \bfseries Root@3 & \bfseries Any & \bfseries All & \bfseries Comp.'
    return '\n'.join([
        r'\begin{table}[!htbp]', r'\ablationcolor', r'\centering', r'\small',
        r'\renewcommand{\arraystretch}{1.10}', r'\setlength{\tabcolsep}{3pt}',
        r'\begin{tabular}{lrrrr}', r'\toprule', header + r' \\', r'\midrule',
        *rows, r'\bottomrule', r'\end{tabular}', r'\caption{' + caption + '}',
        r'\label{' + label + '}', r'\end{table}', ''])


def metric_rows(groups, keys, labels):
    rows = []
    for index, model in enumerate(MODELS):
        if index:
            rows.append(r'\midrule')
        rows.append(r'\multicolumn{5}{l}{\bfseries ' + NAMES[model] + r'} \\')
        values = groups[model]['rows']
        for key, label in zip(keys, labels):
            entries = [marked(values[key][metric], [values[k][metric] for k in keys], metric)
                       for metric in METRICS]
            rows.append(label + ' & ' + ' & '.join(entries) + r' \\')
    return rows


def build():
    data = json.loads(SOURCE.read_text())
    assert data['counts']['pending'] == 0 and data['counts']['analysis_errors'] == 0
    t = data['tables']
    expected = set(t['selectors']['llama']['case_uids'])
    assert len(expected) == 80
    for model in MODELS:
        groups = [t['selectors'][model], *t['capacities'][model].values(),
                  t['prefixes']['native-core'][model]]
        for group in groups:
            assert len(group['case_uids']) == 80 and set(group['case_uids']) == expected
        for cap in t['capacities'][model].values():
            rows = cap['rows']
            for key in rows:
                assert math.isclose(rows[key]['compression'], rows['full']['compression'])
                assert math.isclose(rows[key]['root_at_3'], rows['full']['root_at_3'])
        assert t['selectors'][model]['rows']['full'] == t['prefixes']['native-core'][model]['rows']['60']

    parts = [
        '% Generated by output/ablation_revision_20261011/build_appendix.py.',
        '% Frozen values SHA256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        r'\begin{ablationadded}',
        r'\subsection{Dynamic Core Replacement Across Backbones}',
        r'\label{app:new_core_ablation}',
        r'''
We extend paired core replay to Llama 3.1-8B-Instruct, Qwen3.5-9B, and Kimi-VL-A3B, with one Full run per model--case. Each model uses the same 80 injected variants: four templates applied to 20 source SCCs across CUAD, SEC, BGB, and Debian. Each run uses 60 rollouts, four-node windows, internal concurrency four, and temperature 0.4. These 240 trajectories form the ablation cohort, separate from the historical main-experiment results. Tables in this and the next three subsections report percentages averaged over 80 cases per model; the 20 source SCCs are the independent sampling units.

To isolate replacement, both policies receive the same ordered evidence proposals. Dynamic allows earlier admissions to be replaced; locked retains admitted nodes without eviction. For each case, locked capacity is fixed to the final Dynamic output size $k$, and both return exactly $k$ nodes. This paired replay isolates replacement at fixed evidence and retained-core size. Root@3 uses the shared trajectory ranking and is identical across selectors.
''',
        table(metric_rows(t['selectors'], ['full', 'locked-matched-k'], ['Dynamic (Full)', 'Locked']),
              r'Dynamic versus locked core replay at the default capacity ratio $r=0.45$. Any and All denote Risk-any and Risk-all; Comp. is $100(1-|H|/|S|)$. Evidence and actual output size are matched per case. Bold/underline mark the best/second-best endpoint rate within each model, including ties; compression is descriptive.',
              'tab:new_core_replacement'),
        r'''Dynamic replacement increases Risk-all by 27.50, 23.75, and 5.00 percentage points for Llama, Qwen, and Kimi, respectively (Table~\ref{tab:new_core_replacement}). Risk-any also improves on all three backbones at identical compression. The comparison supports revising the retained core as evidence accumulates, with the largest gains on Llama and Qwen.
''',
        r'\subsection{Core Capacity and Retention}',
        r'\label{app:new_core_capacity}',
        r'''
We replay the same Full evidence at four capacity ratios, $r\in\{0.25,0.35,0.45,0.60\}$, with cap $\min\{|S|,\max(4,\lceil r|S|\rceil)\}$. At each ratio, we recompute the production selector from the recorded evidence. Locked admission matches Dynamic's actual final $k$ case by case. The cap is an upper bound; observed compression is calculated from the actual retained-core size.
''',
    ]
    cap_rows = []
    for index, model in enumerate(MODELS):
        if index:
            cap_rows.append(r'\midrule')
        cap_rows.append(r'\multicolumn{5}{l}{\bfseries ' + NAMES[model] + r'} \\')
        for cap in ('0.25', '0.35', '0.45', '0.6'):
            values = t['capacities'][model][cap]['rows']
            full, locked = values['full'], values['locked-matched-k']
            gain = full['risk_all'] - locked['risk_all']
            assert gain > 0
            cap_rows.append(f'{float(cap):.2f} & ' + r'\tblbest{' + fmt(full['risk_all']) + '} & '
                            + fmt(locked['risk_all']) + f' & $+{gain:.2f}$ & '
                            + fmt(full['compression']) + r' \\')
    parts += [
        table(cap_rows,
              r'Capacity sweep on the same 80 Full trajectories per model. Dynamic and Locked columns report Risk-all; $\Delta$ is their difference in percentage points. Comp. is the shared mean compression of the paired outputs. Bold marks the higher Risk-all within each pair.',
              'tab:new_core_capacity',
              r'\bfseries $r$ & \bfseries Dynamic & \bfseries Locked & \bfseries $\Delta$ & \bfseries Comp.'),
        r'''Dynamic retains complete endpoints more often than locked admission at all 12 model--capacity settings (Table~\ref{tab:new_core_capacity}). Dynamic's Risk-all increases with capacity through $r=0.60$ for Llama and Kimi; Qwen reaches 57.50\% at both $r=0.45$ and $0.60$. The paired gains persist across the tested caps, while the absolute coverage and compression quantify the trade-off in output size.
''',
        r'\subsection{Selection from Shared Evidence}',
        r'\label{app:new_selector_control}',
        r'''
We compare the Full selector with LEA-score while holding the acquired evidence and final output size fixed. LEA-score applies the membership formula in Appendix~\ref{app:revision_lea} to the recorded Full evaluations and returns its top $k$ nodes, where $k$ is Full's actual output size for that case. Its signals are local-subgraph membership, repair-entry and conflict-endpoint counts, plus mean-risk surplus. The comparison isolates final selection on evidence acquired by SA-MCGS.
''',
        table(metric_rows(t['selectors'], ['full', 'lea-score-matched-k'], ['Full', 'LEA-score']),
              r'Full versus LEA-score at matched evidence and actual output size, using the default capacity. Endpoint-rate highlighting follows Table~\ref{tab:new_core_replacement}. Root@3 uses the shared trajectory ranking.',
              'tab:new_selector_lea'),
        r'''Full improves Risk-all over LEA-score by 5.00, 5.00, and 8.75 points on Llama, Qwen, and Kimi (Table~\ref{tab:new_selector_lea}). With the additional mean-risk selector, mean-risk achieves the highest Risk-all on Llama and Qwen, while Full performs best on Kimi (Table~\ref{tab:new_selector_complete}).
''',
        table(metric_rows(t['selectors'], ['full', 'lea-score-matched-k', 'mean-risk-matched-k'],
                          ['Full', 'LEA-score', 'Mean risk']),
              r'Additional selector control on the same evidence and per-case $k$. Mean risk selects nodes by their mean recorded risk score, with SCC-order tie breaking. Bold/underline mark the highest/second-highest distinct endpoint rate within each model; shared ranking and compression remain unchanged.',
              'tab:new_selector_complete'),
        r'\subsection{Evidence Accumulation Across Rollout Prefixes}',
        r'\label{app:new_prefix_analysis}',
        r'''
We reconstruct the native Full core after 15, 30, 45, and 60 completed rollout events from each stored 60-rollout trajectory. These four checkpoints measure evidence accumulation within each trajectory, with the selector, evidence thresholds, and nominal capacity ratio held fixed.
''',
        table(metric_rows(t['prefixes']['native-core'], ['15', '30', '45', '60'], ['15', '30', '45', '60']),
              r'Native Full outputs reconstructed at four rollout prefixes. Each row averages the same 80 cases for its model. Root@3, Risk-any (Any), Risk-all (All), and compression (Comp.) are percentages. Bold/underline identify the highest/second-highest distinct endpoint rate across prefixes within each model; compression describes the evolving output size.',
              'tab:new_native_prefixes',
              r'\bfseries Prefix & \bfseries Root@3 & \bfseries Any & \bfseries All & \bfseries Comp.'),
        r'''From 15 to 60 events, native Risk-all rises from 51.25\% to 62.50\% on Llama, 33.75\% to 57.50\% on Qwen, and 13.75\% to 35.00\% on Kimi (Table~\ref{tab:new_native_prefixes}). The corresponding cores retain more nodes, quantifying the coverage--compression trade-off as search accumulates evidence. This trajectory analysis complements the paired replacement comparisons at fixed evidence and output size.
''',
        r'\end{ablationadded}', '',
    ]
    text = '\n'.join(parts)
    assert text.count(r'\begin{table}') == text.count(r'\ablationcolor') == 5
    assert text.count(r'\subsection{') == 4
    TARGET.write_text(text, encoding='utf-8')
    print(json.dumps({'target': str(TARGET), 'tables': 5, 'subsections': 4,
                      'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                      'tex_sha256': hashlib.sha256(TARGET.read_bytes()).hexdigest()}))


if __name__ == '__main__':
    build()
