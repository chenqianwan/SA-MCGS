"""Build the manuscript table from the frozen five-model figure data."""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / 'paper/latex'
DATA = PAPER / 'figures_equal_budget_20261012/figure_source_data.json'
rows = json.loads(DATA.read_text())
models = ['gpt4o', 'qwen25', 'llama', 'qwen35', 'kimi']
methods = ['lea', 'full-scc', 'sa-mcgs']
metrics = ['root_at_3_percent', 'risk_any_percent', 'risk_all_percent', 'compression_percent']
lookup = {(r['model'], r['method']): r for r in rows}
assert len(lookup) == len(rows) == 15
lines = [
    '% Generated by build_table.py from archived five-model results.',
    r'\begin{table*}[t]', r'\centering',
    r'\renewcommand{\arraystretch}{1.02}', r'\small',
    r'\begin{tabular}{L{.23\textwidth}L{.13\textwidth}rrrr}',
    r'\toprule',
    r'\bfseries Model & \bfseries Method & \bfseries \rootthree{} & \bfseries \riskany{} & \bfseries \riskall{} & \bfseries Compression \\',
    r'\midrule',
]
for mi, model in enumerate(models):
    ranks = {metric: sorted({lookup[(model, m)][metric] for m in methods}, reverse=True)
             for metric in metrics}
    for i, method in enumerate(methods):
        row = lookup[(model, method)]
        values = []
        for metric in metrics:
            value = row[metric]
            assert math.isfinite(value) and 0 <= value <= 100
            formatted = f'{value:.2f}'
            if math.isclose(value, ranks[metric][0], abs_tol=1e-10):
                formatted = r'\tblbest{' + formatted + '}'
            elif len(ranks[metric]) > 1 and math.isclose(value, ranks[metric][1], abs_tol=1e-10):
                formatted = r'\tblsecond{' + formatted + '}'
            values.append(formatted)
        name = row['model_label'] if i == 0 else ''
        label = {'lea': 'LEA', 'full-scc': 'Full-SCC', 'sa-mcgs': r'\textbf{\samcgs{}}'}[method]
        if method == 'sa-mcgs':
            lines.append(r'\rowcolor{TableFocus}')
        lines.append(' & '.join([name, label, *values]) + r' \\')
    if mi < len(models) - 1:
        lines.append(r'\midrule')
lines += [r'\bottomrule', r'\end{tabular}',
          r'\caption{Five-backbone comparison with SA-referenced baseline budgets on the same 80 variants per model (\%). \samcgs{} uses fixed historical outputs. Bold/underline mark the highest/second-highest value within each model, including ties. Shading identifies \samcgs{}; higher compression means a smaller core.}',
          r'\label{tab:equal_budget_five_models}', r'\end{table*}']
(PAPER / 'revision_equal_budget_table.tex').write_text('\n'.join(lines) + '\n')
print('Wrote 15 rows and 60 metric values.')
